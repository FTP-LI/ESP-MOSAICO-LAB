"""Convert the scene paths in scenes.json to native RGB565 LVGL data."""
from pathlib import Path
import importlib.util
import json
from PIL import Image, ImageOps

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
spec=importlib.util.spec_from_file_location('pet_art_converter',HERE.parent/'pets'/'convert_assets.py')
packer=importlib.util.module_from_spec(spec)
spec.loader.exec_module(packer)

def main():
    config=json.loads((HERE/'scenes.json').read_text(encoding='utf-8'))
    size=tuple(config['size'])
    if size!=(480,480): raise ValueError('Scene must match the native display size')
    scenes=config['scenes']
    if len(scenes)!=6 or len({s['key'] for s in scenes})!=6:
        raise ValueError('Expected six unique weather scenes')
    body=['/* Generated by assets/weather/convert_assets.py. */','#include "ui_weather_art.h"']
    proof=Image.new('RGB',(size[0]*3,size[1]*2))
    for i,scene in enumerate(scenes):
        source=(HERE/scene['source']).resolve()
        if not source.is_relative_to(HERE): raise ValueError('Scene source outside assets/weather')
        image=ImageOps.fit(Image.open(source).convert('RGB'),size,method=Image.Resampling.LANCZOS)
        body.append(packer.descriptor('tt_weather_'+scene['key'],image,False))
        proof.paste(image,((i%3)*size[0],(i//3)*size[1]))
    body.append('const lv_image_dsc_t *const tt_art_weather[TT_WEATHER_KINDS] = {')
    body.append(f'    [TT_WEATHER_UNKNOWN]=&tt_weather_{config["fallback"]},')
    for scene in scenes: body.append(f'    [{scene["enum"]}]=&tt_weather_{scene["key"]},')
    body.append('};')
    out=ROOT/'main'/'generated'
    (out/'ui_weather_art.c').write_text('\n\n'.join(body)+'\n',encoding='utf-8')
    (out/'ui_weather_art.h').write_text(
        '#pragma once\n#include "lvgl.h"\n#include "weather_model.h"\n'
        'extern const lv_image_dsc_t *const tt_art_weather[TT_WEATHER_KINDS];\n',encoding='utf-8')
    (ROOT/'build-assets').mkdir(exist_ok=True)
    proof.save(ROOT/'build-assets'/'weather-contact.png')
    print(f'Packed six 480x480 RGB565 scenes: {6*480*480*2:,} bytes')

if __name__=='__main__': main()
