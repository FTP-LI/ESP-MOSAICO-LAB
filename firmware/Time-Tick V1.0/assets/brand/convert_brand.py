"""Pack the original transparent wordmark for the welcome screen; no runtime PNG decoder."""
from pathlib import Path
import importlib.util
from PIL import Image, ImageOps

here = Path(__file__).resolve().parent
root = here.parents[1]
spec = importlib.util.spec_from_file_location("asset_pack", here.parent / "pets" / "convert_assets.py")
pack = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pack)
source = Image.open(here / "time-tick-wordmark.png").convert("RGBA")
image = ImageOps.contain(source, (392, 147), Image.Resampling.LANCZOS)
out = root / "main" / "generated"
(out / "ui_brand.h").write_text('#pragma once\n#include "lvgl.h"\nextern const lv_image_dsc_t tt_art_brand;\n', encoding="utf-8")
(out / "ui_brand.c").write_text('/* Generated by assets/brand/convert_brand.py. AI artwork; see assets/brand/README.md. */\n#include "ui_brand.h"\n' + pack.descriptor("tt_art_brand", image, True) + "\n", encoding="utf-8")
print("Wordmark:", image.size, "ARGB8888 bytes:", image.width * image.height * 4)
