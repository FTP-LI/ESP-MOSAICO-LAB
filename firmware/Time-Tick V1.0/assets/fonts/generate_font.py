"""Generate the UI's OFL bitmap subset with Pillow/FreeType (not a build wrapper).

python assets/fonts/generate_font.py build-font/NotoSansCJKsc-Regular.otf
Run after changing Chinese strings. ASCII and every Chinese character in main/**/*.c
are included. Output uses LVGL's uncompressed 4-bpp public font format.
"""
from pathlib import Path
import hashlib
import sys
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1])
expected = '2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'
assert hashlib.sha256(source.read_bytes()).hexdigest() == expected, 'Unexpected font source'
chars = set(chr(i) for i in range(32, 127))
for path in (root / 'main').rglob('*.c'):
    if 'generated' not in path.parts:
        chars.update(c for c in path.read_text(encoding='utf-8') if ord(c) > 127)
chars.update('一二三四五六日月年月星期温度湿度简体中文，。：！？…–℃')
ui_chars = chars.copy()
network_chars = set()
for high in range(0xb0, 0xf8):
    for low in range(0xa1, 0xff):
        try: network_chars.add(bytes((high, low)).decode('gb2312'))
        except UnicodeDecodeError: pass
for size in (16, 18, 24, 52, 84):
    chars = sorted((ui_chars | network_chars) if size == 16 else set('0123456789:- ') if size >= 52 else ui_chars, key=ord)
    font = ImageFont.truetype(str(source), size)
    bitmap, descriptors = [], ['{0}']
    for ch in chars:
        x1, y1, x2, y2 = font.getbbox(ch, anchor='ls')
        w, h = x2-x1, y2-y1
        im = Image.new('L', (max(w, 1), max(h, 1)))
        ImageDraw.Draw(im).text((-x1, -y1), ch, font=font, anchor='ls', fill=255)
        pixels = [round(v * 15 / 255) for v in im.tobytes()] if w*h else []
        index = len(bitmap)
        if len(pixels) % 2: pixels.append(0)
        bitmap.extend((pixels[i] << 4) | pixels[i+1] for i in range(0, len(pixels), 2))
        descriptors.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}' %
                           (index, round(font.getlength(ch)*16), w, h, x1, -y2))
    byte_lines = [','.join('0x%02x'%b for b in bitmap[i:i+24]) for i in range(0,len(bitmap),24)]
    offsets = ','.join(str(ord(ch)-32) for ch in chars)
    body = '/* SPDX-License-Identifier: OFL-1.1\n * Copyright 2014-2021 Adobe (http://www.adobe.com/).\n * Noto Sans CJK SC subset; see assets/fonts/OFL.txt and README.md.\n * Generated by assets/fonts/generate_font.py; do not edit. */\n#include "lvgl.h"\n'
    body += 'static const uint8_t bitmap[]={\n' + ',\n'.join(byte_lines) + '\n};\n'
    body += 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={\n' + ',\n'.join(descriptors) + '\n};\n'
    body += 'static const uint16_t unicode_list[]={' + offsets + '};\n'
    body += 'static const lv_font_fmt_txt_cmap_t cmaps[]={{.range_start=32,.range_length=%d,.glyph_id_start=1,.unicode_list=unicode_list,.list_length=%d,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};\n' % (ord(chars[-1])-31, len(chars))
    body += 'static const lv_font_fmt_txt_dsc_t dsc={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=1,.bpp=4,.bitmap_format=0};\n'
    body += 'extern const lv_font_t tt_font_16;\n' if size in (18,24) else ''
    body += 'const lv_font_t tt_font_%d={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=%d,.base_line=%d,.underline_position=-2,.underline_thickness=1,.dsc=&dsc,.fallback=&%s};\n' % (size, size+4, 4, 'tt_font_16' if size in (18,24) else 'lv_font_montserrat_14')
    (root / 'main' / 'generated' / 'fonts' / ('font_%d.c'%size)).write_text(body, encoding='utf-8')
    print(size, len(chars), 'glyphs;', len(bitmap), 'bitmap bytes')
