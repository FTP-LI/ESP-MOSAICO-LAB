"""Generate small LVGL bitmap fonts from the pinned LVGL Source Han font.

Requires Pillow. Generated C is committed, so regular builds do not need Pillow.
Font-derived output is covered by docs/licenses/SourceHanSansSC-OFL.txt.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'managed_components/lvgl__lvgl/scripts/built_in_font'
text = (ROOT/'main/main.c').read_text(encoding='utf-8') + (ROOT/'configs/default-profiles.json').read_text(encoding='utf-8')
points = sorted(set(range(32, 127)) | {ord(c) for c in text if 127 < ord(c) < 65536})
output = ['/* Generated by tools/generate_fonts.py.',
          ' * Copyright 2014-2021 Adobe. Font-derived data: SIL OFL 1.1.',
          ' * See docs/licenses/SourceHanSansSC-OFL.txt. */', '#include "deck_font.h"']
for size in (16, 20):
    font = ImageFont.truetype(str(SOURCE/'SourceHanSansSC-Normal.otf'), size)
    bitmap, descriptors = [], ['{0}']
    for point in points:
        char = chr(point)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right-left, bottom-top
        offset = len(bitmap)
        if width and height:
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor='ls')
            pixels = [(p + 8)//17 for p in image.tobytes()]
            if len(pixels) % 2: pixels.append(0)
            bitmap.extend((pixels[i] << 4) | pixels[i+1] for i in range(0, len(pixels), 2))
        descriptors.append(f'{{.bitmap_index={offset},.adv_w={round(font.getlength(char)*16)},.box_w={width},.box_h={height},.ofs_x={left},.ofs_y={-bottom}}}')
    prefix = f'deck_{size}'
    output += [f'static const uint8_t {prefix}_bitmap[] = {{']
    output += [','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24)]
    output += ['};', f'static const lv_font_fmt_txt_glyph_dsc_t {prefix}_glyphs[] = {{', ',\n'.join(descriptors), '};',
               f'static const uint16_t {prefix}_unicode[] = {{'+','.join(str(p-32) for p in points)+'};',
               f'static const lv_font_fmt_txt_cmap_t {prefix}_cmaps[] = {{{{.range_start=32,.range_length={points[-1]-31},.glyph_id_start=1,.unicode_list={prefix}_unicode,.list_length={len(points)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};',
               f'static const lv_font_fmt_txt_dsc_t {prefix}_dsc = {{.glyph_bitmap={prefix}_bitmap,.glyph_dsc={prefix}_glyphs,.cmaps={prefix}_cmaps,.cmap_num=1,.bpp=4,.bitmap_format=0}};',
               f'const lv_font_t lv_font_deck_{size} = {{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={size+6},.base_line=5,.subpx=LV_FONT_SUBPX_NONE,.underline_position=-2,.underline_thickness=1,.dsc=&{prefix}_dsc}};']
    print(f'{size}px: {len(points)} glyphs, {len(bitmap)} bitmap bytes')
(ROOT/'main/deck_font.c').write_text('\n'.join(output)+'\n', encoding='utf-8')
license_path = ROOT/'docs/licenses/SourceHanSansSC-OFL.txt'
license_path.parent.mkdir(parents=True, exist_ok=True)
license_path.write_bytes((SOURCE/'font_license/SourceHanSansSC/LICENSE.txt').read_bytes())
