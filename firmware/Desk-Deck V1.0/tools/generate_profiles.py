"""Generate firmware defaults from the same JSON used by the browser prototype."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root/'configs/default-profiles.json').read_text(encoding='utf-8'))
mods = {'CTRL':'KEYBOARD_MODIFIER_LEFTCTRL','SHIFT':'KEYBOARD_MODIFIER_LEFTSHIFT',
        'ALT':'KEYBOARD_MODIFIER_LEFTALT','GUI':'KEYBOARD_MODIFIER_LEFTGUI'}
keys = {'BACKQUOTE':'HID_KEY_GRAVE','TAB':'HID_KEY_TAB'}
media = {'SCAN_PREVIOUS_TRACK':0xb6,'SCAN_NEXT_TRACK':0xb5,'PLAY_PAUSE':0xcd,'MUTE':0xe2,'VOLUME_INCREMENT':0xe9,'VOLUME_DECREMENT':0xea}
icons = {'copy':'COPY','paste':'PASTE','capture':'IMAGE','undo':'LEFT','redo':'RIGHT','desktop':'HOME',
         'play':'PLAY','stop':'STOP','terminal':'LIST','code':'EDIT','search':'EYE_OPEN','command':'KEYBOARD',
         'save':'SAVE','select':'OK','tab':'PLUS','restore':'REFRESH','windows':'LIST','previous':'PREV',
         'next':'NEXT','mute':'MUTE','volumeDown':'VOLUME_MID','volumeUp':'VOLUME_MAX'}
lines = ['// Generated by tools/generate_profiles.py; edit configs/default-profiles.json instead.',
         'static const char *profile_names[4] = {' + ','.join(json.dumps(p['name'],ensure_ascii=False) for p in data['profiles']) + '};',
         'static const deck_key_t defaults[4][6] = {']
for profile in data['profiles']:
    lines.append('    {')
    for button in profile['buttons']:
        action = button['action']; modifier='0'; key='0'; consumer=0
        if action['type'] == 'keyboard':
            modifier = ' | '.join(mods[k] for k in action['keys'] if k in mods) or '0'
            ordinary = [k for k in action['keys'] if k not in mods]
            assert len(ordinary) == 1
            key = keys.get(ordinary[0], 'HID_KEY_'+ordinary[0])
        else: consumer=media[action['usage']]
        label=json.dumps(button['label'],ensure_ascii=False); hint=json.dumps(button['hint'],ensure_ascii=False)
        lines.append(f'        {{{label}, {hint}, LV_SYMBOL_{icons[button["icon"]]}, {{{modifier}, {key}, {consumer}}}}},')
    lines.append('    },')
lines.append('};')
(root/'main/profiles.inc').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated 24 Desk-Deck V1.0 actions')
