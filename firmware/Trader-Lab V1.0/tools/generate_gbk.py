"""Generate GBK codepoint mapping from Python's standard codec; no service needed."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
values=[]
for high in range(0x81,0xff):
    for low in range(0x40,0xff):
        try:
            char=bytes((high,low)).decode('gbk')
            values.append(ord(char))
        except UnicodeDecodeError:
            values.append(0xfffd)
data='\n'.join(','.join(str(c) for c in values[i:i+24])+',' for i in range(0,len(values),24))
source='''// Generated by tools/generate_gbk.py; GBK standard codepoint map.
#include "model.h"
static const uint16_t mapping[]={
'''+data+'''
};
void tl_gbk_utf8(const char *input,size_t length,char *out,size_t capacity)
{
    size_t at=0;
    for(size_t i=0;i<length;i++) {
        unsigned c=(unsigned char)input[i],cp=c;
        if(c>=0x81 && c<=0xfe && i+1<length) {
            unsigned low=(unsigned char)input[++i];
            cp=low>=0x40 && low<=0xfe?mapping[(c-0x81)*191+low-0x40]:0xfffd;
        } else if(c>=128) cp=0xfffd;
        unsigned bytes=cp<128?1:cp<2048?2:3;
        if(at+bytes>=capacity) break;
        if(bytes==1) out[at++]=(char)cp;
        else if(bytes==2) { out[at++]=(char)(0xc0|(cp>>6)); out[at++]=(char)(0x80|(cp&63)); }
        else { out[at++]=(char)(0xe0|(cp>>12)); out[at++]=(char)(0x80|((cp>>6)&63)); out[at++]=(char)(0x80|(cp&63)); }
    }
    if(capacity) out[at]=0;
}
'''
(root/'main/gbk.c').write_text(source,encoding='utf-8')
print(f'GBK map: {len(values)*2} bytes')
